// Math class is part of java.lang package which is in built in jdk.
// wap to use math class


public class math_Inbuilt_06 {
    public static void main(String[] args) {
        System.out.println(Math.PI);
        System.out.println(Math.E);
        System.out.println(Math.pow(2,3.5));
        System.out.println(Math.abs(-4));
        System.out.println(Math.sqrt(16));
        System.out.println(Math.round(3.5)); // uses round off rules
        System.out.println(Math.ceil(-2.2));
        System.out.println(Math.floor(-3.4));  // it reverses its property for negative numbers
        System.out.println(Math.max(17,11));
        System.out.println(Math.min(17,11));

    }
}

